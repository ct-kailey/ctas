'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const script = path.join(root, 'node_modules/vite/bin/vite.js');
if (!fs.existsSync(script)) throw new Error('Build dependencies are missing. Run npm ci first.');
const result = spawnSync(process.execPath, [script, 'build'], { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
console.log('Built the unified AINS workflow application into dist/.');
