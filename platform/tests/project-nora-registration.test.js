'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {createPool,migrate}=require('../server/db');
const {createLedger}=require('../server/ledger');
const {createNoraGitHub}=require('../server/nora-github');
const {createRepositoryAccess}=require('../server/repository-access');
const {createImplementationLedger}=require('../server/implementation-ledger');
test('new project registration is atomic/idempotent and Git reads stay in its Nora workspace',{skip:!process.env.TEST_DATABASE_URL},async t=>{
  const schema='nora_registration_'+randomUUID().replaceAll('-',''),admin=createPool(process.env.TEST_DATABASE_URL);
  await admin.query('CREATE SCHEMA '+schema);
  const pool=createPool({connectionString:process.env.TEST_DATABASE_URL,options:'-c search_path='+schema+',public'});
  t.after(async()=>{await pool.end();await admin.query('DROP SCHEMA '+schema+' CASCADE');await admin.end();});
  await migrate(pool);
  const user=(await pool.query("INSERT INTO users(email,name,password_hash) VALUES('owner@nora.test','owner','unused') RETURNING id")).rows[0].id;
  const ledger=createLedger(pool,{requireNoraWorkspace:true}),workspace='t_project_'+randomUUID().replaceAll('-','');
  const request={name:'Project A',project_kind:'internal_product',nora_workspace_id:workspace,request_id:randomUUID()};
  await assert.rejects(ledger.createProject(user,{name:'missing'}),{code:'NORA_WORKSPACE_ID_INVALID'});
  // Keep the public creation contract's known project kind.
  request.project_kind='unspecified';
  const results=await Promise.all(Array.from({length:4},()=>ledger.createProject(user,request)));
  assert.equal(new Set(results.map(r=>r.id)).size,1);
  const p=results[0].id;
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM projects')).rows[0].n,1);
  assert.equal((await pool.query('SELECT workspace_id FROM project_nora_workspaces WHERE project_id=$1',[p])).rows[0].workspace_id,workspace);
  await assert.rejects(ledger.createProject(user,{...request,name:'Changed'}),{code:'PROJECT_REQUEST_CONFLICT'});
  await assert.rejects(ledger.createProject(user,{...request,request_id:randomUUID()}),{code:'NORA_WORKSPACE_ALREADY_BOUND'});
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM projects')).rows[0].n,1);
  await pool.query("UPDATE project_nora_workspaces SET status='ready',stage='complete',space_id='space_a',connector_id='connector_a' WHERE project_id=$1",[p]);
  const implementation=createImplementationLedger(pool);
  await implementation.saveSettings(p,user,{expected_version:1,goal:'test scoped Git',repository_url:'https://github.com/acme/only-project-a',base_branch:'main'});
  const calls=[];let defaultRepo='acme/only-project-a',returnedRepo=defaultRepo;
  const provider={async callTool(input){calls.push(input);assert.equal(input.projectId,p);assert.equal(input.workspaceId,workspace);
    if(input.name==='get_connector')return{id:'connector_a',provider:'github',config:{defaultRepo},operations:[{id:'list_commits',params:['repo','branch','per_page']}]};
    assert.equal(input.name,'invoke_connector');assert.equal(input.arguments.args.repo,'acme/only-project-a');assert.equal(input.arguments.args.branch,'refs/heads/main');
    return[{sha:'a'.repeat(40),html_url:'https://github.com/'+returnedRepo+'/commit/'+'a'.repeat(40),commit:{message:'Only this project'}}];
  }};
  const git=createNoraGitHub({pool,provider});
  const access=createRepositoryAccess(pool,{implementation,noraGit:git,encryptionKey:Buffer.alloc(32,7).toString('base64'),serverToken:'must_not_be_used',fetchImpl:async()=>{throw Error('Direct GitHub fallback must not run');}});
  assert.equal((await access.status(p,user)).credential_source,'nora');
  assert.equal((await access.verify(p,user)).repository_check.credential_source,'nora');
  assert.equal((await git.history(p,user)).commits.length,1);
  defaultRepo='acme/different-project';
  await assert.rejects(git.verify(p),{code:'NORA_GITHUB_REPOSITORY_MISMATCH'});
  defaultRepo='acme/only-project-a';returnedRepo='acme/different-project';
  await assert.rejects(git.history(p,user),{code:'NORA_GITHUB_REPOSITORY_MISMATCH'});
  await assert.rejects(access.save(p,user,{expected_version:0,expected_settings_version:2,token:'github_pat_should_not_save_1234'}),{code:'NORA_GITHUB_CONNECTION_MANAGED'});
  assert.ok(calls.every(c=>!JSON.stringify(c).includes('must_not_be_used')));
});
